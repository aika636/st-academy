// Хелпер тестов (не тест): пресет из файла, разрешённый под род героя.
//
// Файлы пресетов хранят строки, зависящие от рода, парами `{female, male}`
// (`core/gender`). Ядро видит уже разрешённый пресет — как в `index.js`, — поэтому
// тесты, которые читают файл в обход расширения, разрешают пары так же.

import { resolvePreset } from '../core/gender.mjs';

/** JSON-текст пресета → пресет под род героя (по умолчанию женский). */
export const parsePreset = (text, gender = 'f') => resolvePreset(JSON.parse(text), gender);
